// Opciones del selector de país: España primero y el resto ordenado por el
// nombre en el idioma activo. El value siempre es el nombre en español para
// que el email interno y el lead lleguen normalizados.
export function getCountryOptions(locale: string): { value: string; label: string }[] {
  const label = (c: CountryEntry) => (locale === "en" ? c.en : c.es);
  const spain = COUNTRIES.find((c) => c.es === ESPANA)!;
  const rest = COUNTRIES.filter((c) => c !== spain).sort((a, b) =>
    label(a).localeCompare(label(b), locale)
  );
  return [spain, ...rest].map((c) => ({ value: c.es, label: label(c) }));
}

/** Valores admitidos para el campo país (el value del selector es siempre el nombre en español). */
export function isPaisValido(pais: string): boolean {
  return COUNTRIES.some((c) => c.es === pais);
}

/** Valores admitidos para el campo provincia. */
export function isProvinciaValida(provincia: string): boolean {
  return PROVINCIAS_ESPANA.includes(provincia);
}
